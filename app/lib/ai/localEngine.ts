import type { AIMessage, StreamOptions } from './types';

export const SYSTEM_PROMPT = `You are Aria, the AI SEO strategist inside the AI Startup workspace.
You help marketers turn a rough topic, keyword, or URL into publish-ready SEO assets:
titles, meta descriptions, keyword clusters, content outlines, and FAQs.
Be concrete and skimmable. Prefer short headings and bullet lists over long prose.`;

const FILLER_WORDS = new Set([
  'the', 'a', 'an', 'and', 'or', 'for', 'to', 'of', 'in', 'on', 'with',
  'about', 'my', 'our', 'your', 'please', 'write', 'create', 'generate',
  'help', 'me', 'make', 'give', 'some', 'a', 'blog', 'post', 'article',
  'seo', 'keyword', 'content', 'page', 'website', 'site',
  'plan', 'strategy', 'ideas', 'list', 'tips',
]);

const titleCase = (value: string): string =>
  value
    .split(/\s+/)
    .filter(Boolean)
    .map((word) => word.charAt(0).toUpperCase() + word.slice(1))
    .join(' ');

/** Best-effort extraction of the "subject" of the request. */
export function extractSubject(messages: AIMessage[]): string {
  const lastUser = [...messages].reverse().find((m) => m.role === 'user');
  const raw = (lastUser?.content ?? '').replace(/\s+/g, ' ').trim();

  if (!raw) {
    return 'your product';
  }

  const words = raw
    .split(/[\s,.;:!?]+/)
    .map((w) => w.toLowerCase().replace(/[^a-z0-9-]/g, ''))
    .filter((w) => w.length > 2 && !FILLER_WORDS.has(w));

  const subject = words.slice(0, 4).join(' ').trim();

  return subject || raw.slice(0, 60);
}

const slugify = (value: string): string =>
  value
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/(^-|-$)/g, '');

function buildTitleIdeas(subject: string): string[] {
  const s = titleCase(subject);
  return [
    `${s}: The Complete 2025 Guide`,
    `How to Master ${s} (Without Guesswork)`,
    `10 ${s} Best Practices That Actually Move Rankings`,
    `${s} Explained: A Practical Playbook for Teams`,
    `Why ${s} Matters for Your Organic Growth`,
  ];
}

function buildMetaDescriptions(subject: string): string[] {
  const s = titleCase(subject);
  return [
    `Discover how ${subject} drives qualified organic traffic. A practical, data-backed guide with templates you can ship today.`,
    `Everything you need to know about ${s} — checklists, examples, and the metrics that matter. Read the step-by-step guide.`,
    `Learn ${subject} in under 10 minutes. Actionable tips to improve visibility, rankings, and conversions.`,
  ];
}

function buildKeywords(subject: string): string[] {
  const base = subject.toLowerCase();
  return [
    base,
    `${base} guide`,
    `how to ${base}`,
    `best ${base} practices`,
    `${base} checklist`,
    `${base} examples`,
    `${base} strategy`,
    `${base} tools`,
    `what is ${base}`,
    `${base} for startups`,
  ];
}

function buildOutline(subject: string): string[] {
  const s = titleCase(subject);
  return [
    `Introduction — why ${subject} is a growth lever right now`,
    `What ${s} means (and what it does not)`,
    `The 3 pillars of a winning ${subject} strategy`,
    `Step-by-step: building your ${s} plan`,
    `Common mistakes and how to avoid them`,
    `Tools, templates, and a 30-day action plan`,
    `FAQs about ${s}`,
  ];
}

function buildFaqs(subject: string): string[] {
  const s = titleCase(subject);
  return [
    `What is ${subject} in simple terms?`,
    `How long does it take to see results from ${subject}?`,
    `Do I need paid tools to get started with ${s}?`,
    `How do I measure the impact of ${s}?`,
  ];
}

/** Deterministic, dependency-free reply used when no external AI provider is configured. */
export function buildLocalReply(messages: AIMessage[]): string {
  const subject = extractSubject(messages);
  const slug = slugify(subject) || 'your-topic';

  const bullet = (items: string[]) => items.map((i) => `- ${i}`).join('\n');
  const numbered = (items: string[]) =>
    items.map((i, index) => `${index + 1}. ${i}`).join('\n');

  return `Here's a publish-ready SEO plan for **${subject}**.

## Title ideas
${bullet(buildTitleIdeas(subject))}

## Meta descriptions
${bullet(buildMetaDescriptions(subject))}

## Keyword cluster
${bullet(buildKeywords(subject).slice(0, 6))}

**Suggested URL slug:** \`/${slug}\`

## Content outline
${numbered(buildOutline(subject))}

## FAQ block (great for rich results)
${bullet(buildFaqs(subject))}

---
_Generated by the built-in Aria engine. Add an \`OPENAI_API_KEY\` (or an OpenAI-compatible \`AI_BASE_URL\`) to route these requests to a live model._`;
}

function chunkText(text: string, size = 24): string[] {
  const chunks: string[] = [];

  for (let i = 0; i < text.length; i += size) {
    chunks.push(text.slice(i, i + size));
  }

  return chunks;
}

const delay = (ms: number) => new Promise((resolve) => setTimeout(resolve, ms));

/** Streams the local reply token-chunk by token-chunk to mimic live generation. */
export async function* streamLocalReply(
  messages: AIMessage[],
  options: StreamOptions = {},
): AsyncGenerator<string> {
  const text = buildLocalReply(messages);

  for (const chunk of chunkText(text)) {
    if (options.signal?.aborted) {
      return;
    }

    yield chunk;
    await delay(18);
  }
}
